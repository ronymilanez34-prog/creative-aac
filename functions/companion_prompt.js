const LOW_ENERGY_NOTE = `# מצב אנרגיה נמוכה — כרגע פעיל
למשתמש קשה עכשיו. הצע 2 אפשרויות בלבד, פשוטות מאוד. משפט אחד קצר ב-say.
בלי שאלות מורכבות, בלי אישורים אלא אם הכרחי. רוגע מעל הכול.`;

/**
 * Builds the `system` blocks for the Messages API, structured for prompt
 * caching: the stable prefix (instructions + profile) carries a
 * `cache_control` breakpoint, and everything that changes per turn (the
 * creation so far, the low-energy note) comes after it, so a turn never
 * invalidates the cached prefix.
 *
 * Honest note on economics: Haiku 4.5's minimum cacheable prefix is 4096
 * tokens; below that the marker is a silent no-op (no error, no charge).
 * Today's instructions alone are under it — caching starts paying for
 * itself automatically once real user profiles (vocabulary, scripts,
 * preferences) fatten the prefix. Cache reads then cost ~10% of input.
 */
// Live pace signal from the app (computed from recent selection latencies).
// Rendered AFTER the cache breakpoint so it never invalidates the prefix.
const PACE_NOTES = {
  flowing:
    "# קצב עכשיו: בשטף\nהמשתמש בוחר מהר וברצף. קצר מאוד את התרומה שלך — או תור ליווי שקט. הוא מוביל.",
  hesitant:
    "# קצב עכשיו: מהוסס\nהמשתמש לוקח את הזמן. האט, הרגע, אל תציף. אפשר לכלול צ'יפ מנוחה. אין שום לחץ להתקדם.",
};

// A creation longer than this (or one that already has a summary) asks the
// model to refresh creation_summary each turn — the rolling summary that
// lets the app send only the newest pieces. Matches the app-side switch in
// lib/services/creation_context.dart.
const SUMMARY_ASK_CHARS = 700;

function buildSystemPrompt({ profile, creationSoFar, creationSummary, sceneSoFar, declinedOptions, lowEnergy, paceHint }) {
  const profileText =
    profile && String(profile).trim() ? String(profile).trim() : "אין עדיין פרופיל — פגוש אותו בעדינות ולמד מהתגובות.";
  const creationText =
    creationSoFar && String(creationSoFar).trim() ? String(creationSoFar).trim() : "עדיין ריק — זו ההתחלה.";
  const summaryText =
    creationSummary && String(creationSummary).trim() ? String(creationSummary).trim() : "";

  const lowEnergyBlock = lowEnergy ? `${LOW_ENERGY_NOTE}\n\n` : "";
  // Own-property check: a hostile paceHint like "constructor" must not
  // resolve through the prototype chain into the prompt.
  const paceNote = Object.prototype.hasOwnProperty.call(PACE_NOTES, paceHint)
    ? PACE_NOTES[paceHint]
    : "";
  const paceBlock = paceNote ? `${paceNote}\n\n` : "";

  // With a summary in play the model sees summary + newest pieces; the ask
  // to refresh creation_summary rides whenever the creation is long enough
  // to need one (or one already exists — it must not go stale).
  const askSummary = summaryText || creationText.length > SUMMARY_ASK_CHARS;
  const summaryAskBlock = askSummary
    ? "# הערת מערכת: היצירה ארוכה — עדכן בתור הזה את creation_summary (תקציר היצירה כולה).\n\n"
    : "";
  const creationBlock = summaryText
    ? `# תקציר היצירה עד כה\n${summaryText}\n\n# הקטעים האחרונים של היצירה\n${creationText}`
    : `# היצירה עד עכשיו\n${creationText}`;
  // A picture creation's state lives in the scene, not the text — with a
  // scene present, an "empty" creation is NOT a fresh start.
  const sceneText =
    sceneSoFar && String(sceneSoFar).trim() ? String(sceneSoFar).trim() : "";
  const sceneBlock = sceneText
    ? `\n\n# הסצנה כפי שצוירה עד עכשיו (יצירה ויזואלית פעילה — לא מתחילים מחדש)\n${sceneText}`
    : "";

  // The session's walked-past list: everything that was on screen when the
  // user chose "משהו אחר". The one list the model must never draw from.
  const declined = Array.isArray(declinedOptions)
    ? declinedOptions.filter((d) => String(d || "").trim())
    : [];
  const declinedBlock = declined.length
    ? `\n\n# נדחה בסשן הזה — אל תציע שוב\nכשהאפשרויות האלה הוצעו, המשתמש בחר "משהו אחר". אל תציע אותן שוב בסשן הזה, בשום ניסוח, אלא אם הוא מבקש אותן בעצמו:\n${declined.map((d) => `- ${String(d).trim()}`).join("\n")}`
    : "";

  return [
    { type: "text", text: INSTRUCTIONS },
    {
      type: "text",
      text: `# הפרופיל של המשתמש/ת\n${profileText}`,
      cache_control: { type: "ephemeral" },
    },
    {
      type: "text",
      text: `${lowEnergyBlock}${paceBlock}${summaryAskBlock}${creationBlock}${sceneBlock}${declinedBlock}`,
    },
  ];
}

module.exports = { buildSystemPrompt };
